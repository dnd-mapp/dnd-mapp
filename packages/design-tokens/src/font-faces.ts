import { readFile } from 'node:fs/promises';
import { join, posix } from 'node:path';
import arial from '@capsizecss/metrics/arial';
import courierNew from '@capsizecss/metrics/courierNew';
import { fromFile } from '@capsizecss/unpack/fs';
import { format, resolveConfig } from 'prettier';
import { fallbackFamily, fonts, type FallbackFont, type FontFamily, type FontStyle } from './fonts.ts';

/** The metrics of a font that its fallback face needs, in the units of its em square. */
export interface FontMetrics {
    /** The height above the baseline that the font reserves for a line. */
    ascent: number;
    /** The depth below the baseline that the font reserves for a line, as a negative number. */
    descent: number;
    /** The gap that the font adds between lines. */
    lineGap: number;
    /** The size of the em square. */
    unitsPerEm: number;
    /** The average width of a character, weighted by how often it appears in English text. */
    xWidthAvg: number;
}

/** A face of a Fontsource CSS file, which loads one subset of one style. */
export interface FontFace {
    /** The subset of the face, such as `latin-ext`. */
    subset: string;
    /** The style of the face. */
    style: FontStyle;
    /** The weight range of the variable font, such as `200 800`. */
    weight: string;
    /** The name of its WOFF2 file in the `files` folder of the package. */
    file: string;
    /** The code points that the subset covers, so a browser downloads it only for a page that uses one. */
    unicodeRange: string;
}

/** The descriptors of a fallback face, each a percentage, that scale a local font to the metrics of a family. */
export interface FallbackOverrides {
    /** Scales the fallback, so its average character width matches the family's. */
    sizeAdjust: string;
    /** The ascent of the family, as a share of the scaled size. */
    ascentOverride: string;
    /** The descent of the family, as a share of the scaled size. */
    descentOverride: string;
    /** The line gap of the family, as a share of the scaled size. */
    lineGapOverride: string;
}

const fallbackMetrics: Readonly<Record<FallbackFont, FontMetrics>> = { 'Arial': arial, 'Courier New': courierNew };

/** The CSS file of each style in a Fontsource package of a variable font. */
const styleFiles: Readonly<Record<FontStyle, string>> = { normal: 'wght.css', italic: 'wght-italic.css' };

/** The subset whose file the fallback metrics come from, since it holds the characters of English text. */
const metricsSubset = 'latin';

const indent = '    ';

const header =
    '/* Generated by design-tokens:build from src/fonts.ts and the Fontsource packages. Change src/fonts.ts, not this file. */';

/**
 * Generates the `@font-face` rules of the font families: one per subset and style, and a fallback face per family.
 * Prettier formats the rules as `format-check` expects, since it wraps the long `src` and `unicode-range` values.
 * @param root - The folder of the package, whose `node_modules` holds the Fontsource packages.
 * @param families - The families to load.
 * @returns The contents of `fonts.css`.
 */
export async function buildFonts(root: string, families: readonly FontFamily[] = fonts): Promise<string> {
    const rules = await Promise.all(families.map(async (font) => formatFamily(font, root)));
    const path = join(root, 'css', 'fonts.css');
    const options = await resolveConfig(path, { editorconfig: true });

    return format(`${header}\n\n${rules.join('\n')}`, { ...options, filepath: path });
}

async function formatFamily(font: FontFamily, root: string) {
    const folder = join(root, 'node_modules', font.package);
    const faces = await Promise.all(
        font.styles.map(async (style) =>
            parseFaces(await readFile(join(folder, styleFiles[style]), 'utf8'), font.package, style),
        ),
    );
    const metricsFace = faces.flat().find((face) => face.style === 'normal' && face.subset === metricsSubset);

    if (metricsFace === undefined) {
        throw new Error(`${font.package} ships no ${metricsSubset} subset in the normal style to read metrics from.`);
    }
    const metrics = await fromFile(join(folder, 'files', metricsFace.file));

    return [
        ...faces.flat().map((face) => formatFace(font, face)),
        formatFallback(font, fallbackOverrides(metrics, fallbackMetrics[font.fallback])),
    ].join('\n');
}

/**
 * Reads the faces of a CSS file of a Fontsource package of a variable font.
 * @param css - The contents of the file, such as `wght.css`.
 * @param packageName - The name of the package, whose last segment starts the name of each font file.
 * @param style - The style that the file holds.
 * @returns The faces, in the order of the file.
 */
export function parseFaces(css: string, packageName: string, style: FontStyle): FontFace[] {
    const id = packageName.slice(packageName.lastIndexOf('/') + 1);
    const suffix = `-wght-${style}.woff2`;

    return [...css.matchAll(/@font-face\s*\{([^}]*)\}/g)].map(([, body = '']) => {
        const file = readDescriptor(body, /src:\s*url\(\.\/files\/([^)]+)\)/, packageName);

        if (!file.startsWith(`${id}-`) || !file.endsWith(suffix)) {
            throw new Error(`${packageName} names a font file ${file}, which isn't ${id}-<subset>${suffix}.`);
        }
        if (readDescriptor(body, /font-style:\s*([^;]+);/, packageName) !== style) {
            throw new Error(`${packageName} declares ${file} in the CSS of its ${style} style, but not as ${style}.`);
        }
        return {
            subset: file.slice(id.length + 1, -suffix.length),
            style,
            weight: readDescriptor(body, /font-weight:\s*([^;]+);/, packageName),
            file,
            unicodeRange: readDescriptor(body, /unicode-range:\s*([^;]+);/, packageName)
                .split(',')
                .map((range) => range.trim())
                .join(', '),
        };
    });
}

function readDescriptor(body: string, pattern: RegExp, packageName: string) {
    const value = pattern.exec(body)?.[1]?.trim();

    if (value === undefined) {
        throw new Error(`${packageName} has a @font-face rule that doesn't match ${String(pattern)}.`);
    }
    return value;
}

/**
 * Computes the descriptors that scale a fallback font to a family, so the swap from one to the other moves little
 * text. The average character width sets the size, and the vertical metrics follow at that size, as Capsize computes
 * them.
 * @param font - The metrics of the family.
 * @param fallback - The metrics of the local font that stands in for it.
 * @returns The descriptors of the fallback face.
 */
export function fallbackOverrides(font: FontMetrics, fallback: FontMetrics): FallbackOverrides {
    const sizeAdjust = font.xWidthAvg / font.unitsPerEm / (fallback.xWidthAvg / fallback.unitsPerEm);
    const emSquare = font.unitsPerEm * sizeAdjust;

    return {
        sizeAdjust: percentage(sizeAdjust),
        ascentOverride: percentage(font.ascent / emSquare),
        descentOverride: percentage(Math.abs(font.descent) / emSquare),
        lineGapOverride: percentage(font.lineGap / emSquare),
    };
}

function percentage(ratio: number) {
    return `${String(Math.round(ratio * 10000) / 100)}%`;
}

function formatFace(font: FontFamily, face: FontFace) {
    const url = posix.join('..', 'node_modules', font.package, 'files', face.file);

    return formatRule(`${font.family}, ${face.style}, ${face.subset}`, [
        `font-family: '${font.family}';`,
        `font-style: ${face.style};`,
        `font-weight: ${face.weight};`,
        'font-display: swap;',
        `src: url('${url}') format('woff2');`,
        `unicode-range: ${face.unicodeRange};`,
    ]);
}

function formatFallback(font: FontFamily, overrides: FallbackOverrides) {
    return formatRule(`${fallbackFamily(font)}: ${font.fallback}, scaled to the metrics of ${font.family}`, [
        `font-family: '${fallbackFamily(font)}';`,
        `src: local('${font.fallback}');`,
        `size-adjust: ${overrides.sizeAdjust};`,
        `ascent-override: ${overrides.ascentOverride};`,
        `descent-override: ${overrides.descentOverride};`,
        `line-gap-override: ${overrides.lineGapOverride};`,
    ]);
}

function formatRule(comment: string, declarations: readonly string[]) {
    return `/* ${comment} */\n@font-face {\n${declarations.map((line) => `${indent}${line}`).join('\n')}\n}\n`;
}
