import { buildCss } from './build.ts';

// A small export in the format of Penpot 2.19.1, with a token of each kind that the build treats on its own.
const exported = {
    'primitives': {
        color: {
            neutral: {
                19: { $value: '#101419', $type: 'color', $description: 'oklch(0.19 0.012 248)' },
                94: { $value: '#E8ECEF', $type: 'color' },
            },
        },
    },
    'color/dark': {
        color: { background: { page: { $value: '{color.neutral.19}', $type: 'color' } } },
        shadow: {
            raised: {
                $value: [
                    { offsetX: '0px', offsetY: '1px', blur: '3px', spread: '0px', color: '#00000047', inset: false },
                ],
                $type: 'shadow',
            },
        },
    },
    'color/light': {
        color: { background: { page: { $value: '{color.neutral.94}', $type: 'color' } } },
        shadow: {
            raised: {
                $value: [
                    { offsetX: '0px', offsetY: '1px', blur: '3px', spread: '0px', color: '#0F172A12', inset: false },
                ],
                $type: 'shadow',
            },
        },
    },
    'base': {
        'space': { 16: { $value: '16px', $type: 'spacing' } },
        'size': { half: { $value: '50%', $type: 'sizing' } },
        'border-width': { default: { $value: '1px', $type: 'borderWidth' } },
        'font': {
            family: { heading: { $value: ['Manrope'], $type: 'fontFamilies' } },
            weight: { extrabold: { $value: '800', $type: 'fontWeights' } },
            size: { 13: { $value: '13px', $type: 'fontSizes' } },
        },
        'letter-spacing': {
            none: { $value: '0px', $type: 'letterSpacing' },
            eyebrow: { $value: '1.5px', $type: 'letterSpacing' },
        },
        'text-case': { none: { $value: 'none', $type: 'textCase' } },
        'typography': {
            h1: {
                $value: {
                    fontFamilies: ['{font.family.heading}'],
                    fontSizes: '{font.size.h1}',
                    fontWeights: '{font.weight.extrabold}',
                    letterSpacing: '{letter-spacing.none}',
                    lineHeights: '1.12',
                    textCase: '{text-case.none}',
                    textDecoration: 'none',
                },
                $type: 'typography',
                $description: 'Page title, one per page',
            },
        },
    },
    'viewport/desktop': {
        font: { size: { h1: { $value: '54px', $type: 'fontSizes' } } },
    },
    'viewport/mobile': {
        font: { size: { h1: { $value: '34px', $type: 'fontSizes' } } },
    },
    '$themes': [],
    '$metadata': { activeThemes: [], activeSets: [] },
};

/**
 * Reads the declarations of the rule that a comment names, such as `color/dark`.
 * @param css - The generated CSS.
 * @param sets - The comment above the rule, which lists its sets.
 * @returns The lines between the braces of the rule.
 */
function rule(css: string, sets: string) {
    const match = new RegExp(String.raw`/\* ${sets} \*/\n:root \{\n([^}]*)\n\}`).exec(css);

    return match?.[1]?.split('\n').map((line) => line.trim()) ?? [];
}

describe('buildCss', () => {
    /**
     * Builds the CSS of the export.
     * @param modify - Changes a copy of the export before the build, for a test that needs other tokens.
     * @returns The contents of `tokens.css`.
     */
    async function setupTest(modify?: (tokens: typeof exported) => void) {
        const tokens = structuredClone(exported);

        modify?.(tokens);
        return await buildCss(tokens);
    }

    it('starts with a comment that says how the file is made', async () => {
        const css = await setupTest();

        expect(css).toMatch(/^\/\* Generated by design-tokens:build from tokens\.json\./);
    });

    describe('sets', () => {
        it('puts primitives and base on :root, then color/dark, then viewport/desktop', async () => {
            const css = await setupTest();

            expect([...css.matchAll(/\/\* (.+) \*\/\n(.+) \{/g)].map(([, sets, selector]) => [sets, selector])).toEqual(
                [
                    ['primitives, base', ':root'],
                    ['color/dark', ':root'],
                    ['viewport/desktop', ':root'],
                ],
            );
        });

        it('declares each token in the rule of its set', async () => {
            const css = await setupTest();

            expect(rule(css, 'primitives, base')).toContain('--space-16: 1rem;');
            expect(rule(css, 'color/dark')).toContain('--color-background-page: var(--color-neutral-19);');
            expect(rule(css, 'viewport/desktop')).toContain('--font-size-h1: 3.375rem;');
        });

        it('takes the tokens of color/dark, not those of color/light', async () => {
            const css = await setupTest();

            expect(css).not.toContain('var(--color-neutral-94)');
            expect(css).not.toContain('#0f172a12');
        });

        it('takes the tokens of viewport/desktop, not those of viewport/mobile', async () => {
            const css = await setupTest();

            expect(css).not.toContain('2.125rem');
        });
    });

    describe('names', () => {
        it('names each variable after the path of its token, in kebab case', async () => {
            const css = await setupTest();

            expect(css).toContain('--color-neutral-19: #101419;');
            expect(css).toContain('--letter-spacing-eyebrow: ');
        });

        it('keeps references as var()', async () => {
            const css = await setupTest();

            expect(rule(css, 'color/dark')).toContain('--color-background-page: var(--color-neutral-19);');
        });

        it('writes the description of a token as a comment above it', async () => {
            const css = await setupTest();

            expect(css).toContain('/** oklch(0.19 0.012 248) */\n    --color-neutral-19: #101419;');
        });
    });

    describe('units', () => {
        it.each([
            ['a spacing', '--space-16: 1rem;'],
            ['a font size', '--font-size-13: 0.8125rem;'],
            ['a letter spacing', '--letter-spacing-eyebrow: 0.09375rem;'],
        ])('converts %s from px to rem at 16 px to 1 rem', async (_, declaration) => {
            const css = await setupTest();

            expect(css).toContain(declaration);
        });

        it('writes a size of 0 px without a unit', async () => {
            const css = await setupTest();

            expect(css).toContain('--letter-spacing-none: 0;');
        });

        it('keeps border widths in px', async () => {
            const css = await setupTest();

            expect(css).toContain('--border-width-default: 1px;');
        });

        it('keeps a size in another unit than px', async () => {
            const css = await setupTest();

            expect(css).toContain('--size-half: 50%;');
        });
    });

    describe('typography', () => {
        it('declares one variable for each property of a typography token', async () => {
            const css = await setupTest();

            expect(rule(css, 'primitives, base').filter((line) => line.startsWith('--typography-h1-'))).toEqual([
                '--typography-h1-font-family: var(--font-family-heading);',
                '--typography-h1-font-size: var(--font-size-h1);',
                '--typography-h1-font-weight: var(--font-weight-extrabold);',
                '--typography-h1-letter-spacing: var(--letter-spacing-none);',
                '--typography-h1-line-height: 1.12;',
                '--typography-h1-text-case: var(--text-case-none);',
                '--typography-h1-text-decoration: none;',
            ]);
        });

        it('writes the description of a typography token once', async () => {
            const css = await setupTest();

            expect(css.match(/Page title, one per page/g)).toHaveLength(1);
        });

        it('quotes a font family whose name holds a space', async () => {
            const css = await setupTest((tokens) => {
                tokens.base.font.family.heading.$value = ['Source Sans 3'];
            });

            expect(css).toContain("--font-family-heading: 'Source Sans 3';");
        });
    });

    it('writes a shadow as one box-shadow value', async () => {
        const css = await setupTest();

        expect(rule(css, 'color/dark')).toContain('--shadow-raised: 0px 1px 3px 0px #00000047;');
    });
});
