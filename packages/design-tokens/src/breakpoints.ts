/**
 * The narrowest window that gets the Desktop sizes, as ADR 0008 records. It is in `em`, so a reader who enlarges the
 * text keeps the Mobile sizes up to a wider window, as the `rem` sizes grow with it.
 */
export const desktopBreakpoint = '64em';

const header = '// Generated by design-tokens:build. Change the breakpoint in src/breakpoints.ts, not this file.';

/**
 * Generates the Sass partial that carries the breakpoints into the media queries of component styles, since no custom
 * property can appear in a media query.
 * @returns The contents of `breakpoints.scss`.
 */
export function buildBreakpoints(): string {
    return `${header}\n\n$breakpoint-desktop: ${desktopBreakpoint};\n`;
}
