import { expandTypesMap, register } from '@tokens-studio/sd-transforms';
import StyleDictionary from 'style-dictionary';
import type { FormatFnArguments, TransformedToken } from 'style-dictionary/types';
import { createPropertyFormatter } from 'style-dictionary/utils';
import { findSource, mergeSets, splitSets, type TokenSets } from './sets.ts';
import { normalizeTokens } from './normalize.ts';

/** A rule of the generated CSS, which declares the tokens of some sets of the export. */
export interface Block {
    /** The selector of the rule. */
    selector: string;
    /** The names of the sets whose tokens the rule declares. */
    sets: readonly string[];
}

/**
 * The rules of `tokens.css`. They put the sets of Penpot's active themes, Dark and Desktop, on `:root`, as ADR 0006
 * records. ADR 0008 moves Light and Mobile into rules of their own.
 */
export const blocks: readonly Block[] = [
    { selector: ':root', sets: ['primitives', 'base'] },
    { selector: ':root', sets: ['color/dark'] },
    { selector: ':root', sets: ['viewport/desktop'] },
];

/** The size of 1 rem in px, which browsers use unless the reader sets another font size. */
const remInPx = 16;

const header = '/* Generated by design-tokens:build from tokens.json. Change the tokens in Penpot, not this file. */';

/**
 * Converts a size in px to rem. Border widths keep their px, so a 1 px line neither rounds to 0 nor grows with the text.
 * Style Dictionary's own `size/pxToRem` converts any unit as if it were px, so the build converts px only.
 */
const pxToRem = {
    type: 'value',
    transitive: true,
    filter: (token: TransformedToken) =>
        (token.$type === 'dimension' || token.$type === 'fontSize') && originalType(token) !== 'borderWidth',
    transform: (token: TransformedToken) => {
        const value = String(token.$value);
        const px = /^(-?\d*\.?\d+)px$/.exec(value)?.[1];

        if (px === undefined) {
            return value;
        }
        return Number(px) === 0 ? '0' : `${String(Number(px) / remInPx)}rem`;
    },
} as const;

/**
 * Reads the type that Penpot gave a token, which the `tokens-studio` preprocessor replaces with its DTCG type.
 * @param token - The token to read.
 * @returns The Tokens Studio type, or `undefined` when the preprocessor kept the type.
 */
function originalType(token: TransformedToken): unknown {
    const extensions = token['$extensions'] as Record<string, { originalType?: unknown } | undefined> | undefined;

    return extensions?.['studio.tokens']?.originalType;
}

/**
 * Generates the CSS custom properties of a token export.
 * @param exported - The parsed contents of `tokens.json`, the single-file token export of Penpot.
 * @param rules - The rules to write, each with the sets it declares.
 * @returns The contents of `tokens.css`.
 */
export async function buildCss(
    exported: Readonly<Record<string, unknown>>,
    rules: readonly Block[] = blocks,
): Promise<string> {
    const sets = splitSets(exported);
    const names = rules.flatMap((rule) => rule.sets);
    const tokens = mergeSets(sets, names);

    normalizeTokens(tokens);
    await register(StyleDictionary);

    const dictionary = new StyleDictionary({
        tokens,
        preprocessors: ['tokens-studio'],
        expand: { include: ['typography'], typesMap: expandTypesMap },
        log: { verbosity: 'silent', warnings: 'error' },
        hooks: {
            transforms: { 'dnd-mapp/size/pxToRem': pxToRem },
            formats: { 'dnd-mapp/css': (args) => formatCss(args, sets, names, rules) },
        },
        platforms: {
            css: {
                transformGroup: 'tokens-studio',
                transforms: ['name/kebab', 'dnd-mapp/size/pxToRem'],
                files: [{ destination: 'tokens.css', format: 'dnd-mapp/css' }],
            },
        },
    });
    const [file] = await dictionary.formatPlatform('css');

    return String(file?.output);
}

function formatCss(
    { dictionary }: FormatFnArguments,
    sets: TokenSets,
    names: readonly string[],
    rules: readonly Block[],
): string {
    // The comment goes above its declaration, since one after a long value would push the line past the width that
    // Prettier allows.
    const formatToken = createPropertyFormatter({
        format: 'css',
        dictionary,
        outputReferences: true,
        usesDtcg: true,
        formatting: { indentation: '    ', commentPosition: 'above' },
    });
    // Each token that Style Dictionary expands repeats the description of its typography token, so only the first
    // property of each typography token keeps it.
    const described = new Set<string>();
    const css = rules.map((rule) => {
        // The declarations keep the order of the export, since custom properties resolve wherever they are declared.
        const declarations = dictionary.allTokens.flatMap((token) => {
            const source = findSource(sets, names, token.path);

            if (source === undefined || !rule.sets.includes(source.set)) {
                return [];
            }
            const sourcePath = source.path.join('.');
            const repeatsDescription = described.has(sourcePath);

            described.add(sourcePath);
            return [formatToken(repeatsDescription ? withoutDescription(token) : token)];
        });

        return `/* ${rule.sets.join(', ')} */\n${rule.selector} {\n${declarations.join('\n')}\n}\n`;
    });

    return `${header}\n\n${css.join('\n')}`;
}

function withoutDescription(token: TransformedToken): TransformedToken {
    const copy = { ...token };

    delete copy.$description;
    delete copy.comment;
    return copy;
}
