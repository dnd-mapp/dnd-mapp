import { expandTypesMap, register } from '@tokens-studio/sd-transforms';
import StyleDictionary from 'style-dictionary';
import type { FormatFnArguments, TransformedToken } from 'style-dictionary/types';
import { createPropertyFormatter } from 'style-dictionary/utils';
import { desktopBreakpoint } from './breakpoints.ts';
import { fontStack } from './fonts.ts';
import { findSource, isToken, mergeSets, overlaySets, splitSets, type TokenGroup, type TokenSets } from './sets.ts';
import { normalizeTokens } from './normalize.ts';

/** A rule of the generated CSS, which declares the tokens of some sets of the export. */
export interface Block {
    /**
     * The selectors of the rule, outermost first: a media query wraps the selector after it. A block whose only selector
     * is `:root` applies unless a later block overrides it.
     */
    selectors: readonly string[];
    /** The names of the sets whose tokens the rule declares. */
    sets: readonly string[];
    /** The `color-scheme` that the rule sets, so the parts the browser draws, such as scrollbars, match the theme. */
    colorScheme?: 'dark' | 'light';
}

/**
 * The rules of `tokens.css`, as ADR 0008 records. Dark and Mobile sit on `:root`. Light overrides Dark when the device
 * prefers light and `data-theme` doesn't ask for dark, or when `data-theme` asks for light. Desktop overrides Mobile
 * from the desktop breakpoint up.
 */
export const blocks: readonly Block[] = [
    { selectors: [':root'], sets: ['primitives', 'base'] },
    { selectors: [':root'], sets: ['color/dark'], colorScheme: 'dark' },
    { selectors: [':root'], sets: ['viewport/mobile'] },
    {
        selectors: ['@media (prefers-color-scheme: light)', ":root:not([data-theme='dark'])"],
        sets: ['color/light'],
        colorScheme: 'light',
    },
    { selectors: [":root[data-theme='light']"], sets: ['color/light'], colorScheme: 'light' },
    { selectors: [`@media (min-width: ${desktopBreakpoint})`, ':root'], sets: ['viewport/desktop'] },
];

/** The size of 1 rem in px, which browsers use unless the reader sets another font size. */
const remInPx = 16;

const indent = '    ';

const header = '/* Generated by design-tokens:build from tokens.json. Change the tokens in Penpot, not this file. */';

/**
 * Converts a size in px to rem. Border widths keep their px, so a 1 px line neither rounds to 0 nor grows with the text.
 * Style Dictionary's own `size/pxToRem` converts any unit as if it were px, so the build converts px only.
 */
const pxToRem = {
    type: 'value',
    transitive: true,
    filter: (token: TransformedToken) =>
        (token.$type === 'dimension' || token.$type === 'fontSize') && originalType(token) !== 'borderWidth',
    transform: (token: TransformedToken) => {
        const value = String(token.$value);
        const px = /^(-?\d*\.?\d+)px$/.exec(value)?.[1];

        if (px === undefined) {
            return value;
        }
        return Number(px) === 0 ? '0' : `${String(Number(px) / remInPx)}rem`;
    },
} as const;

/**
 * Writes each `fontFamilies` token as the font stack of its family, as ADR 0010 records. Penpot renders the first family
 * of a token only, so the stack comes from `src/fonts.ts`. A typography token that references the family keeps its
 * `var()`, since the transform skips a token whose value is a reference.
 */
const fontStackTransform = {
    type: 'value',
    filter: (token: TransformedToken) => token.$type === 'fontFamily',
    transform: (token: TransformedToken) => fontStack(String((token.original as { $value: unknown }).$value)),
} as const;

/**
 * Reads the type that Penpot gave a token, which the `tokens-studio` preprocessor replaces with its DTCG type.
 * @param token - The token to read.
 * @returns The Tokens Studio type, or `undefined` when the preprocessor kept the type.
 */
function originalType(token: TransformedToken) {
    const extensions = token['$extensions'] as Record<string, { originalType?: unknown } | undefined> | undefined;

    return extensions?.['studio.tokens']?.originalType;
}

/**
 * Generates the CSS custom properties of a token export.
 * @param exported - The parsed contents of `tokens.json`, the single-file token export of Penpot.
 * @param rules - The rules to write, each with the sets it declares.
 * @returns The contents of `tokens.css`.
 */
export async function buildCss(
    exported: Readonly<Record<string, unknown>>,
    rules: readonly Block[] = blocks,
): Promise<string> {
    const sets = splitSets(exported);
    const defaults = rules.filter(isDefault).flatMap((rule) => rule.sets);

    for (const set of sets.values()) {
        checkFontFamilies(set);
    }

    await register(StyleDictionary);

    // Each rule resolves its tokens against the default sets, with its own sets in place of those they override.
    const css = await Promise.all(
        rules.map(async (rule) =>
            formatRule(rule, await declare(sets, overlaySets(sets, defaults, rule.sets), rule.sets)),
        ),
    );

    return `${header}\n\n${css.join('\n')}`;
}

/**
 * Fails on a `fontFamilies` token whose family the font config lacks. Style Dictionary would catch the error of the
 * transform that writes the stack, and report only that a transform failed.
 * @param tree - The token tree to check.
 */
function checkFontFamilies(tree: TokenGroup) {
    for (const node of Object.values(tree)) {
        if (!isToken(node)) {
            checkFontFamilies(node);
        } else if (node.$type === 'fontFamilies') {
            for (const family of [node.$value].flat()) {
                if (!String(family).startsWith('{')) {
                    fontStack(String(family));
                }
            }
        }
    }
}

function isDefault(rule: Block) {
    return rule.selectors.length === 1 && rule.selectors[0] === ':root';
}

/**
 * Formats the tokens of some sets as declarations.
 * @param sets - The sets of the export.
 * @param names - The names of the sets that resolve the tokens.
 * @param declared - The names of the sets whose tokens to declare.
 * @returns The declarations, each indented one level.
 */
async function declare(sets: TokenSets, names: readonly string[], declared: readonly string[]) {
    const tokens = mergeSets(sets, names);

    normalizeTokens(tokens);

    const dictionary = new StyleDictionary({
        tokens,
        preprocessors: ['tokens-studio'],
        expand: { include: ['typography'], typesMap: expandTypesMap },
        log: { verbosity: 'silent', warnings: 'error' },
        hooks: {
            transforms: { 'dnd-mapp/size/pxToRem': pxToRem, 'dnd-mapp/font/stack': fontStackTransform },
            formats: { 'dnd-mapp/declarations': (args) => formatDeclarations(args, sets, names, declared) },
        },
        platforms: {
            css: {
                transformGroup: 'tokens-studio',
                transforms: ['name/kebab', 'dnd-mapp/size/pxToRem', 'dnd-mapp/font/stack'],
                files: [{ destination: 'tokens.css', format: 'dnd-mapp/declarations' }],
            },
        },
    });
    const [file] = await dictionary.formatPlatform('css');

    return String(file?.output);
}

function formatDeclarations(
    { dictionary }: FormatFnArguments,
    sets: TokenSets,
    names: readonly string[],
    declared: readonly string[],
) {
    // The comment goes above its declaration, since one after a long value would push the line past the width that
    // Prettier allows.
    const formatToken = createPropertyFormatter({
        format: 'css',
        dictionary,
        outputReferences: true,
        usesDtcg: true,
        formatting: { indentation: indent, commentPosition: 'above' },
    });
    // Each token that Style Dictionary expands repeats the description of its typography token, so only the first
    // property of each typography token keeps it.
    const described = new Set<string>();

    // The declarations keep the order of the export, since custom properties resolve wherever they are declared.
    return dictionary.allTokens
        .flatMap((token) => {
            const source = findSource(sets, names, token.path);

            if (source === undefined || !declared.includes(source.set)) {
                return [];
            }
            const sourcePath = source.path.join('.');
            const repeatsDescription = described.has(sourcePath);

            described.add(sourcePath);
            return [formatToken(repeatsDescription ? withoutDescription(token) : token)];
        })
        .join('\n');
}

/**
 * Wraps declarations in the selectors of their rule.
 * @param rule - The rule to write.
 * @param declarations - The declarations of its tokens, each indented one level.
 * @returns The rule, with its sets in a comment above it.
 */
function formatRule(rule: Block, declarations: string) {
    const colorScheme = rule.colorScheme === undefined ? [] : [`${indent}color-scheme: ${rule.colorScheme};`];
    // Each selector but the innermost wraps a rule, which it indents one more level.
    const nested = rule.selectors.reduceRight(
        (inner, selector, index) =>
            `${selector} {\n${index === rule.selectors.length - 1 ? inner : indented(inner)}\n}`,
        [...colorScheme, declarations].join('\n'),
    );

    return `/* ${rule.sets.join(', ')} */\n${nested}\n`;
}

function indented(text: string) {
    return text
        .split('\n')
        .map((line) => (line === '' ? line : `${indent}${line}`))
        .join('\n');
}

function withoutDescription(token: TransformedToken) {
    const copy = { ...token };

    delete copy.$description;
    delete copy.comment;
    return copy;
}
